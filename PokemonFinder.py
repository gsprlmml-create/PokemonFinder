# -----------------------------------------------------------------------------
# 2. Carga de Modelos y Datos
# -----------------------------------------------------------------------------
@st.cache_resource
def cargar_modelo():
    if not os.path.exists("best.pt"):
        return None
    return YOLO("best.pt")

@st.cache_data
def cargar_datos():
    df_pk = pd.read_csv("pokemon.csv") if os.path.exists("pokemon.csv") else None
    if df_pk is not None:
        df_pk["name_lower"] = df_pk["Name"].str.lower()
        
    df_evo = pd.read_csv("pokemon_evolution.csv") if os.path.exists("pokemon_evolution.csv") else None
    return df_pk, df_evo

model = cargar_modelo()
df_pokemon, df_evolution = cargar_datos()

TRADUCCION_TIPOS = {
    'Normal': 'Normal', 'Fire': 'Fuego', 'Water': 'Agua', 'Grass': 'Planta',
    'Electric': 'Eléctrico', 'Ice': 'Hielo', 'Fighting': 'Lucha', 'Poison': 'Veneno',
    'Ground': 'Tierra', 'Flying': 'Volador', 'Psychic': 'Psíquico', 'Bug': 'Bicho',
    'Rock': 'Roca', 'Ghost': 'Fantasmal', 'Dragon': 'Dragón', 'Dark': 'Siniestro',
    'Steel': 'Acero', 'Fairy': 'Hada'
}

# -----------------------------------------------------------------------------
# 3. Barra Lateral (Sidebar) - Único punto para subir la imagen
# -----------------------------------------------------------------------------
with st.sidebar:
    st.markdown("### 🎛️ Panel de Control")
    archivo_imagen = st.file_uploader("Sube la imagen del Pokémon", type=["jpg", "jpeg", "png"])
    st.markdown("---")
    st.caption("Pokédex Inteligente · YOLOv8n-cls")
    if model is None:
        st.error("⚠️ Falta el archivo `best.pt`")
    if df_pokemon is None:
        st.error("⚠️ Falta el archivo `pokemon.csv`")

# -----------------------------------------------------------------------------
# 4. Panel Principal
# -----------------------------------------------------------------------------
st.markdown(f"""
<div class="encabezado">
  <h1>Pokédex Inteligente con YOLOv8</h1>
  <p>Clasificación visual por IA, análisis de estadísticas y comparativa de especies.</p>
</div>
""", unsafe_allow_html=True)

pokemon_detectado = None
imagen_cargada = None

if archivo_imagen is not None:
    imagen_cargada = Image.open(archivo_imagen)
    if model is not None:
        results = model(imagen_cargada)
        top_1_idx = results[0].probs.top1
        detectado_nombre = results[0].names[top_1_idx]
        confianza_val = results[0].probs.top1conf.item() * 100
        
        if df_pokemon is not None:
            match = df_pokemon[df_pokemon["name_lower"] == detectado_nombre.lower()]
            if not match.empty:
                pokemon_detectado = match.iloc[0]

if pokemon_detectado is not None:
    # Definir las 3 pestañas solicitadas
    tabs = st.tabs(["⚡ Ficha Principal y Stats", "🧬 Evolución", "⚔️ Comparativa de Poder"])
    
    # --- PESTAÑA 1: FICHA PRINCIPAL Y STATS ---
    with tabs[0]:
        col1, col2 = st.columns([1, 1.6], gap="large")
        
        with col1:
            st.subheader("📸 Imagen Analizada")
            st.image(imagen_cargada, use_container_width=True)
            st.success(f"¡Detectado: **{pokemon_detectado['Name']}**!")
            st.metric(label="Confianza del Modelo", value=f"{confianza_val:.1f}%")
            
        with col2:
            st.subheader("📊 Atributos y Estadísticas Base")
            
            t1 = pokemon_detectado["Type1"]
            t2 = pokemon_detectado.get("Type2")
            tipos = [t1]
            if pd.notna(t2) and str(t2).strip() != "" and str(t2).lower() != "nan":
                tipos.append(t2)
            tipos_es = [TRADUCCION_TIPOS.get(str(t).strip(), str(t).strip()) for t in tipos]
            
            st.markdown(f"**Tipo(s):** `{' / '.join(tipos_es)}` &nbsp;|&nbsp; **Generación:** `{pokemon_detectado['Generation']}`")
            
            stats_dict = {
                "PS (HP)": int(pokemon_detectado['HP']),
                "Ataque (Attack)": int(pokemon_detectado['Attack']),
                "Defensa (Defense)": int(pokemon_detectado['Defense']),
                "At. Esp. (Sp. Atk)": int(pokemon_detectado['Sp. Atk']),
                "Def. Esp. (Sp. Def)": int(pokemon_detectado['Sp. Def']),
                "Velocidad (Speed)": int(pokemon_detectado['Speed'])
            }
            
            for label, val in stats_dict.items():
                col_s1, col_s2 = st.columns([3, 1])
                with col_s1:
                    st.markdown(f"**{label}**")
                    st.progress(min(val / 180.0, 1.0))
                with col_s2:
                    st.markdown(f"<h3 style='margin:0; text-align:right;'>{val}</h3>", unsafe_allow_html=True)
            
            st.markdown(f"**Total Estadísticas Base:** `{int(pokemon_detectado['Total'])}`")

    # --- PESTAÑA 2: EVOLUCIÓN ---
    with tabs[1]:
        st.subheader(f"🧬 Línea Evolutiva de {pokemon_detectado['Name']}")
        
        if df_evolution is not None and df_pokemon is not None:
            poke_id = pokemon_detectado['ID']
            evos = df_evolution[df_evolution['id'] == poke_id]
            
            if not evos.empty:
                for _, row in evos.iterrows():
                    evolved_id = row['evolved_species_id']
                    evo_match = df_pokemon[df_pokemon['ID'] == evolved_id]
                    if not evo_match.empty:
                        evo_name = evo_match.iloc[0]['Name']
                        nivel_req = row['minimum_level']
                        trigger = row['evolution_trigger_id']
                        
                        detalle = f"➔ Evoluciona a **{evo_name}**"
                        if pd.notna(nivel_req):
                            detalle += f" al alcanzar el **Nivel {int(nivel_req)}**"
                        elif trigger == 2:
                            detalle += " mediante **Intercambio**"
                        elif pd.notna(row['trigger_item_id']):
                            detalle += " usando un **Objeto especial**"
                        else:
                            detalle += " bajo condiciones específicas"
                            
                        st.info(detalle)
            else:
                st.info(f"**{pokemon_detectado['Name']}** no registra evoluciones posteriores en la base de datos.")
        else:
            st.warning("No se encontró el archivo `pokemon_evolution.csv`.")

    # --- PESTAÑA 3: COMPARATIVA DE PODER ---
    with tabs[2]:
        st.subheader("⚔️ Comparativa de Estadísticas")
        st.markdown(f"Compara el poder base de **{pokemon_detectado['Name']}** con cualquier otro Pokémon de la base de datos.")
        
        lista_nombres = df_pokemon["Name"].tolist()
        # Seleccionar por defecto otro pokemon para comparar o el mismo
        rival_seleccionado = st.selectbox("Selecciona el Pokémon rival para comparar:", lista_nombres, index=min(1, len(lista_nombres)-1))
        
        rival_data = df_pokemon[df_pokemon["Name"] == rival_seleccionado].iloc[0]
        
        categorias = ['HP', 'Ataque', 'Defensa', 'At. Esp.', 'Def. Esp.', 'Velocidad']
        valores_detectado = [
            pokemon_detectado['HP'], pokemon_detectado['Attack'], pokemon_detectado['Defense'],
            pokemon_detectado['Sp. Atk'], pokemon_detectado['Sp. Def'], pokemon_detectado['Speed']
        ]
        valores_rival = [
            rival_data['HP'], rival_data['Attack'], rival_data['Defense'],
            rival_data['Sp. Atk'], rival_data['Sp. Def'], rival_data['Speed']
        ]
        
        fig = go.Figure()
        fig.add_trace(go.Scatterpolar(
            r=valores_detectado, theta=categorias, fill='toself', name=pokemon_detectado['Name'],
            line=dict(color=AZUL)
        ))
        fig.add_trace(go.Scatterpolar(
            r=valores_rival, theta=categorias, fill='toself', name=rival_data['Name'],
            line=dict(color=COBRE)
        ))
        fig.update_layout(
            polar=dict(radialaxis=dict(visible=True, range=[0, 250])),
            showlegend=True, height=500, margin=dict(l=40, r=40, t=40, b=40)
        )
        st.plotly_chart(fig, use_container_width=True)

else:
    st.info("👈 Sube una imagen de un Pokémon en la barra lateral para iniciar el análisis automático y activar las pestañas.")

