def num(x, dec=1):
    """Formato numérico chileno: punto para miles y coma para decimales."""
    try:
        texto = f"{x:,.{dec}f}"
        return texto.replace(",", "X").replace(".", ",").replace("X", ".")
    except:
        return str(x)

@st.cache_resource
def cargar_modelo():
    """Carga el modelo YOLOv8 entrenado (best.pt)."""
    model_path = "best.pt"
    if not os.path.exists(model_path):
        return None
    return YOLO(model_path)

@st.cache_data
def cargar_base_pokemon():
    """Carga los datos desde el archivo pokemon.csv proporcionado."""
    csv_path = "pokemon.csv"
    if os.path.exists(csv_path):
        df = pd.read_csv(csv_path)
        # Normalizar nombres para facilitar búsquedas insensibles a mayúsculas/minúsculas
        df["name_lower"] = df["pokemon_name"].str.lower()
        return df
    return None

model = cargar_modelo()
df_pokemon = cargar_base_pokemon()

